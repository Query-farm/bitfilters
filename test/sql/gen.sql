CREATE TABLE big_filter_test (
    event_ts TIMESTAMP,
    user_id VARCHAR,
    user_created_at TIMESTAMP
);
INSERT INTO big_filter_test
SELECT
    RANGE AS event_ts,
    SUBSTR(MD5(CAST(FLOOR(RANDOM() * 500_000) AS VARCHAR)), 1, 6) AS user_id,
    TIMESTAMP '2015-01-01' + RANDOM() * (TIMESTAMP '2025-12-31' - TIMESTAMP '2015-01-01') AS user_created_at
FROM RANGE(TIMESTAMP '2020-01-01', TIMESTAMP '2025-12-31', INTERVAL '1' SECOND);